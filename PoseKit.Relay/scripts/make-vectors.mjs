// Generates protocol/vectors.json: fixed inputs and outputs that the C# client and the worker tests both check, so
// the two sides agree on key ids, inbox ids, the socket auth string and the peer-message crypto.
// Run once with `node scripts/make-vectors.mjs`; the output is committed. Re-running makes new keys and nonces.
import { writeFileSync } from "node:fs";
import { webcrypto as crypto } from "node:crypto";

const enc = new TextEncoder();
const b64u = (bytes) => Buffer.from(bytes).toString("base64url");
const hex = (bytes) => Buffer.from(bytes).toString("hex");
const sha256Hex = async (text) => hex(new Uint8Array(await crypto.subtle.digest("SHA-256", enc.encode(text))));
const canonical = (jwk) => `{"crv":"P-256","kty":"EC","x":"${jwk.x}","y":"${jwk.y}"}`;

async function device() {
  const pair = await crypto.subtle.generateKey({ name: "ECDH", namedCurve: "P-256" }, true, ["deriveBits"]);
  const jwk = await crypto.subtle.exportKey("jwk", pair.privateKey);
  return { d: jwk.d, x: jwk.x, y: jwk.y, id: await sha256Hex(canonical(jwk)), privateKey: pair.privateKey, publicKey: pair.publicKey };
}

const a = await device();
const b = await device();
const [low, high] = a.id < b.id ? [a, b] : [b, a];
const nonceLow = crypto.getRandomValues(new Uint8Array(16));
const nonceHigh = crypto.getRandomValues(new Uint8Array(16));

const shared = new Uint8Array(await crypto.subtle.deriveBits({ name: "ECDH", public: b.publicKey }, a.privateKey, 256));
const salt = new Uint8Array([...nonceLow, ...nonceHigh]);
const hkdfKey = await crypto.subtle.importKey("raw", shared, "HKDF", false, ["deriveBits"]);
const keyBytes = new Uint8Array(await crypto.subtle.deriveBits(
  { name: "HKDF", hash: "SHA-256", salt, info: enc.encode("posekit-relay-message-v1") }, hkdfKey, 256));

const plaintext = JSON.stringify({ type: "queue", name: "Kittylingus" });
const seq = 7;
const sentAt = 1794700000;
const aad = `posekit-frame-v1\n${low.id}\n${high.id}\n${seq}\n${sentAt}`;
const iv = crypto.getRandomValues(new Uint8Array(12));
const aesKey = await crypto.subtle.importKey("raw", keyBytes, "AES-GCM", false, ["encrypt"]);
const ciphertext = new Uint8Array(await crypto.subtle.encrypt({ name: "AES-GCM", iv, additionalData: enc.encode(aad) }, aesKey, enc.encode(plaintext)));

const vectors = {
  note: "Generated by scripts/make-vectors.mjs. Device keys are P-256; a device signs with ECDSA and agrees keys with ECDH using the same key pair.",
  deviceKeys: [low, high].map((k) => ({ d: k.d, x: k.x, y: k.y, deviceKeyId: k.id })),
  socketAuth: {
    deviceKeyId: low.id,
    nonce: "AAECAwQFBgcICQoLDA0ODw",
    baseString: `posekit-socket-v1\n${low.id}\nAAECAwQFBgcICQoLDA0ODw`,
  },
  inboxIds: await Promise.all(["Aria Moon@Lich", "Sadonia Velvet@Zodiark"].map(async (name) => ({
    character: name,
    inboxId: await sha256Hex(`posekit-inbox-v1|${name}`),
  }))),
  peerMessage: {
    sharedSecretHex: hex(shared),
    nonceLow: b64u(nonceLow),
    nonceHigh: b64u(nonceHigh),
    keyHex: hex(keyBytes),
    fromDeviceKeyId: low.id,
    toDeviceKeyId: high.id,
    seq,
    sentAt,
    aad,
    iv: b64u(iv),
    plaintext,
    ciphertext: b64u(ciphertext),
  },
};

writeFileSync(new URL("../protocol/vectors.json", import.meta.url), JSON.stringify(vectors, null, 2) + "\n");
console.log("wrote protocol/vectors.json");
